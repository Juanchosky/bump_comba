CREATE TRIGGER custom_content_set_updated_at
  BEFORE UPDATE ON public.custom_content
  FOR EACH ROW EXECUTE FUNCTION custom_content_marcar_edicion();

CREATE TRIGGER trg_limpiar_thumb_episodio
  BEFORE INSERT OR UPDATE ON public.custom_content
  FOR EACH ROW EXECUTE FUNCTION limpiar_thumb_episodio();

CREATE TRIGGER trg_limpiar_thumbs_de_la_serie
  AFTER INSERT OR UPDATE ON public.custom_content
  FOR EACH ROW EXECUTE FUNCTION limpiar_thumbs_de_la_serie();

