CREATE OR REPLACE FUNCTION public.custom_content_marcar_edicion()
  RETURNS trigger LANGUAGE plpgsql AS $$
begin
  new.updated_at = now();
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION public.increment_m3u_connections(target_id uuid)
  RETURNS void LANGUAGE plpgsql
  SECURITY DEFINER SET search_path TO 'public', 'pg_temp' AS $$
begin
  update public.m3u_load_balancer
     set current_connections = coalesce(current_connections, 0) + 1
   where id = target_id;
end;
$$;

CREATE OR REPLACE FUNCTION public.limpiar_thumb_episodio()
  RETURNS trigger LANGUAGE plpgsql AS $$
begin
  if new.type = 'episode' and new.thumbnail_url is not null
     and exists (select 1 from public.custom_content p
                  where p.id = new.parent_id and p.thumbnail_url is not null)
  then
    new.thumbnail_url := null;
  end if;
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION public.limpiar_thumbs_de_la_serie()
  RETURNS trigger LANGUAGE plpgsql AS $$
begin
  if new.type = 'series' and new.thumbnail_url is not null then
    update public.custom_content
       set thumbnail_url = null
     where parent_id = new.id
       and type = 'episode'
       and thumbnail_url is not null;
  end if;
  return null;
end;
$$;

CREATE OR REPLACE FUNCTION public.limpiar_tv_pairings()
  RETURNS void LANGUAGE sql
  SECURITY DEFINER SET search_path TO 'public' AS $$
  delete from public.tv_pairings
   where expires_at < now() - interval '1 hour';
$$;

